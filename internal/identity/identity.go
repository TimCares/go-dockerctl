// Package identity manages the age identities (key files) that SOPS uses to decrypt secrets.
package identity

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"time"

	"filippo.io/age"
	"github.com/TimCares/go-see"
	"github.com/getsops/sops/v3"
	"go.uber.org/zap"

	"github.com/TimCares/go-dockerctl"
	internalSOPS "github.com/TimCares/go-dockerctl/internal/identity/sops"
	"github.com/TimCares/go-dockerctl/internal/utils"
)

var AgeRecipientPattern = regexp.MustCompile(`^age1[a-z0-9^1bio]{58}$`)

// ageKeyFileSubpath mirrors the layout SOPS uses for its own default age key file.
const ageKeyFileSubpath = "sops/age/keys.txt"

// AgeKeyFile is the age key file inside dir.
func AgeKeyFile(dir string) string {
	return filepath.Join(dir, ageKeyFileSubpath)
}

func checkKeyFileExists(identityPath string) (bool, error) {
	_, err := os.Stat(identityPath)
	if err == nil {
		return true, nil
	}
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	return false, fmt.Errorf("checking if key file exists: %w", err)
}

func getRecipientFromExistingIdentity(identityPath string) (string, error) {
	b, err := os.ReadFile(identityPath)
	if err != nil {
		return "", fmt.Errorf("found existing identity, but could not read it: %w", err)
	}

	// age errors embed the offending line on parsing errors, which may contain the private key.
	safeError := fmt.Errorf("found existing identity at %s, but encountered an error when parsing the recipient", identityPath)

	identities, err := age.ParseIdentities(bytes.NewReader(b))
	if err != nil {
		return "", safeError
	}

	for _, id := range identities {
		if x25519, ok := id.(*age.X25519Identity); ok {
			return x25519.Recipient().String(), nil
		}
	}

	return "", safeError
}

func makeKeyFileContents(identity *age.X25519Identity) []byte {
	timestamp := time.Now().Format("2006-01-02 15:04:05 MST")

	keyFileContents := fmt.Sprintf(
		"# Generated by dockerctl %s\n# Timestamp %s\n# public key: %s\n%s\n",
		dockerctl.Version,
		timestamp,
		identity.Recipient().String(),
		identity.String(),
	)

	return []byte(keyFileContents)
}

func writeKeyFile(identityPath string, data []byte) error {
	f, err := os.OpenFile(identityPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, utils.SecretFilePerm)
	if err != nil {
		return fmt.Errorf("creating key file: %w", err)
	}

	_, writeErr := f.Write(data)
	closeErr := f.Close()
	if err := errors.Join(writeErr, closeErr); err != nil {
		if removeErr := os.Remove(identityPath); removeErr != nil { // Do not surface error as there is nothing we can do.
			zap.L().Debug("could not remove private key file after writing failed", zap.String("file", identityPath))
		}
		return fmt.Errorf("writing key file: %w", err)
	}

	return nil
}

// MaybeCreateNewAgeIdentity returns the recipient (public key) of the identity at identityPath,
// generating a new identity first if none exists.
func MaybeCreateNewAgeIdentity(ctx context.Context, identityPath string) (string, error) {
	fileExists, err := checkKeyFileExists(identityPath)
	if err != nil {
		return "", err
	}

	if fileExists {
		recipient, err := getRecipientFromExistingIdentity(identityPath)
		if err != nil {
			return "", err
		}
		see.L(ctx).Info("Identity already exists", zap.String("recipient", recipient), zap.String("file", identityPath))
		return recipient, nil
	}

	identity, err := age.GenerateX25519Identity()
	if err != nil {
		return "", fmt.Errorf("generating identity: %w", err)
	}

	parent := filepath.Dir(identityPath)
	if err := os.MkdirAll(parent, utils.SecretDirPerm); err != nil {
		return "", fmt.Errorf("creating parent dirs of key file: %w", err)
	}

	if err := writeKeyFile(identityPath, makeKeyFileContents(identity)); err != nil {
		return "", err
	}

	recipient := identity.Recipient().String()

	return recipient, nil
}

type AddSOPSIdentityArgs struct {
	SopsConfigPath string
	CreationRules  []string
	SopsFilePaths  []string
	Recipient      string
}

func AddSOPSIdentity(ctx context.Context, opts AddSOPSIdentityArgs) error {
	if !AgeRecipientPattern.MatchString(opts.Recipient) {
		return fmt.Errorf("age recipient invalid, expected pattern %s, found %s", AgeRecipientPattern.String(), opts.Recipient)
	}

	if err := addAgeRecipientToSOPSConfig(ctx, opts.SopsConfigPath, opts.CreationRules, opts.Recipient); err != nil {
		return fmt.Errorf("adding recipient to sops config %s: %w", opts.SopsConfigPath, err)
	}

	for _, sopsFilePath := range opts.SopsFilePaths {
		err := updateOrEncrypt(ctx, opts.SopsConfigPath, sopsFilePath)
		if err != nil {
			return fmt.Errorf("adding recipient as recipient to %s: %w", sopsFilePath, err)
		}
	}

	return nil
}

func updateOrEncrypt(ctx context.Context, sopsConfigFilePath string, sopsFilePath string) error {
	if err := internalSOPS.UpdateKeys(sopsConfigFilePath, sopsFilePath); err != nil {
		if errors.Is(err, sops.MetadataNotFound) {
			// File not encrypted yet. Encrypt instead of updatekeys.
			return internalSOPS.Encrypt(sopsConfigFilePath, sopsFilePath)
		}
		return fmt.Errorf("running sops updateKeys: %w", err)
	}
	return nil
}
